var E70NCCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70NCCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70NCCIn(list []string, v string) bool {
	for _, x := range list { if E70NCCLower(x) == v { return true } }
	return false
}

// E70NCCClassify 分类单个令牌。
func E70NCCClassify(tok string) string {
	v := E70NCCLower(tok)
	switch {
	case E70NCCIn(E70NCCBlock, v): return E70NCCClassBlock
	case E70NCCIn(E70NCCWarn, v): return E70NCCClassWarn
	case E70NCCIn(E70NCCAllow, v): return E70NCCClassAllow
	default: return E70NCCClassUnknown
	}
}
