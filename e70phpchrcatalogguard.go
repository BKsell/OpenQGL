var E70PHCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PHCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PHCIn(list []string, v string) bool {
	for _, x := range list { if E70PHCLower(x) == v { return true } }
	return false
}

// E70PHCClassify 分类单个令牌。
func E70PHCClassify(tok string) string {
	v := E70PHCLower(tok)
	switch {
	case E70PHCIn(E70PHCBlock, v): return E70PHCClassBlock
	case E70PHCIn(E70PHCWarn, v): return E70PHCClassWarn
	case E70PHCIn(E70PHCAllow, v): return E70PHCClassAllow
	default: return E70PHCClassUnknown
	}
}
