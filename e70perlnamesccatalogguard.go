var E70PNSAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PNSLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PNSIn(list []string, v string) bool {
	for _, x := range list { if E70PNSLower(x) == v { return true } }
	return false
}

// E70PNSClassify 分类单个令牌。
func E70PNSClassify(tok string) string {
	v := E70PNSLower(tok)
	switch {
	case E70PNSIn(E70PNSBlock, v): return E70PNSClassBlock
	case E70PNSIn(E70PNSWarn, v): return E70PNSClassWarn
	case E70PNSIn(E70PNSAllow, v): return E70PNSClassAllow
	default: return E70PNSClassUnknown
	}
}
