var E70LSCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70LSCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70LSCIn(list []string, v string) bool {
	for _, x := range list { if E70LSCLower(x) == v { return true } }
	return false
}

// E70LSCClassify 分类单个令牌。
func E70LSCClassify(tok string) string {
	v := E70LSCLower(tok)
	switch {
	case E70LSCIn(E70LSCBlock, v): return E70LSCClassBlock
	case E70LSCIn(E70LSCWarn, v): return E70LSCClassWarn
	case E70LSCIn(E70LSCAllow, v): return E70LSCClassAllow
	default: return E70LSCClassUnknown
	}
}
