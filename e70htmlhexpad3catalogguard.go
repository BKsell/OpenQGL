var E70HX3Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70HX3Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70HX3In(list []string, v string) bool {
	for _, x := range list { if E70HX3Lower(x) == v { return true } }
	return false
}

// E70HX3Classify 分类单个令牌。
func E70HX3Classify(tok string) string {
	v := E70HX3Lower(tok)
	switch {
	case E70HX3In(E70HX3Block, v): return E70HX3ClassBlock
	case E70HX3In(E70HX3Warn, v): return E70HX3ClassWarn
	case E70HX3In(E70HX3Allow, v): return E70HX3ClassAllow
	default: return E70HX3ClassUnknown
	}
}
