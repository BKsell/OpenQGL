func E69U02Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69U02In(list []string, v string) bool {
	for _, x := range list { if E69U02Lower(x) == v { return true } }
	return false
}

// E69U02Classify 分类单个令牌。
func E69U02Classify(tok string) string {
	v := E69U02Lower(tok)
	switch {
	case E69U02In(E69U02Block, v): return E69U02ClassBlock
	case E69U02In(E69U02Warn, v): return E69U02ClassWarn
	case E69U02In(E69U02Allow, v): return E69U02ClassAllow
	default: return E69U02ClassUnknown
	}
}
