var E70U10Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70U10Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70U10In(list []string, v string) bool {
	for _, x := range list { if E70U10Lower(x) == v { return true } }
	return false
}

// E70U10Classify 分类单个令牌。
func E70U10Classify(tok string) string {
	v := E70U10Lower(tok)
	switch {
	case E70U10In(E70U10Block, v): return E70U10ClassBlock
	case E70U10In(E70U10Warn, v): return E70U10ClassWarn
	case E70U10In(E70U10Allow, v): return E70U10ClassAllow
	default: return E70U10ClassUnknown
	}
}
