var E70C5LAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70C5LLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70C5LIn(list []string, v string) bool {
	for _, x := range list { if E70C5LLower(x) == v { return true } }
	return false
}

// E70C5LClassify 分类单个令牌。
func E70C5LClassify(tok string) string {
	v := E70C5LLower(tok)
	switch {
	case E70C5LIn(E70C5LBlock, v): return E70C5LClassBlock
	case E70C5LIn(E70C5LWarn, v): return E70C5LClassWarn
	case E70C5LIn(E70C5LAllow, v): return E70C5LClassAllow
	default: return E70C5LClassUnknown
	}
}
