var E69T30Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69T30Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T30In(list []string, v string) bool {
	for _, x := range list { if E69T30Lower(x) == v { return true } }
	return false
}

// E69T30Classify 分类单个令牌。
func E69T30Classify(tok string) string {
	v := E69T30Lower(tok)
	switch {
	case E69T30In(E69T30Block, v): return E69T30ClassBlock
	case E69T30In(E69T30Warn, v): return E69T30ClassWarn
	case E69T30In(E69T30Allow, v): return E69T30ClassAllow
	default: return E69T30ClassUnknown
	}
}
