var E69T32Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69T32Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T32In(list []string, v string) bool {
	for _, x := range list { if E69T32Lower(x) == v { return true } }
	return false
}

// E69T32Classify 分类单个令牌。
func E69T32Classify(tok string) string {
	v := E69T32Lower(tok)
	switch {
	case E69T32In(E69T32Block, v): return E69T32ClassBlock
	case E69T32In(E69T32Warn, v): return E69T32ClassWarn
	case E69T32In(E69T32Allow, v): return E69T32ClassAllow
	default: return E69T32ClassUnknown
	}
}
