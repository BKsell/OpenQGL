var E69C6UAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69C6ULower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69C6UIn(list []string, v string) bool {
	for _, x := range list { if E69C6ULower(x) == v { return true } }
	return false
}

// E69C6UClassify 分类单个令牌。
func E69C6UClassify(tok string) string {
	v := E69C6ULower(tok)
	switch {
	case E69C6UIn(E69C6UBlock, v): return E69C6UClassBlock
	case E69C6UIn(E69C6UWarn, v): return E69C6UClassWarn
	case E69C6UIn(E69C6UAllow, v): return E69C6UClassAllow
	default: return E69C6UClassUnknown
	}
}
