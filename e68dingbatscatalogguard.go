var E68R35Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68R35Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68R35In(list []string, v string) bool {
	for _, x := range list { if E68R35Lower(x) == v { return true } }
	return false
}

// E68R35Classify 分类单个令牌。
func E68R35Classify(tok string) string {
	v := E68R35Lower(tok)
	switch {
	case E68R35In(E68R35Block, v): return E68R35ClassBlock
	case E68R35In(E68R35Warn, v): return E68R35ClassWarn
	case E68R35In(E68R35Allow, v): return E68R35ClassAllow
	default: return E68R35ClassUnknown
	}
}
