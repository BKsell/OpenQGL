var E70PSVAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PSVLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PSVIn(list []string, v string) bool {
	for _, x := range list { if E70PSVLower(x) == v { return true } }
	return false
}

// E70PSVClassify 分类单个令牌。
func E70PSVClassify(tok string) string {
	v := E70PSVLower(tok)
	switch {
	case E70PSVIn(E70PSVBlock, v): return E70PSVClassBlock
	case E70PSVIn(E70PSVWarn, v): return E70PSVClassWarn
	case E70PSVIn(E70PSVAllow, v): return E70PSVClassAllow
	default: return E70PSVClassUnknown
	}
}
