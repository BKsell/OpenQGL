func E70U13Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70U13In(list []string, v string) bool {
	for _, x := range list { if E70U13Lower(x) == v { return true } }
	return false
}

// E70U13Classify 分类单个令牌。
func E70U13Classify(tok string) string {
	v := E70U13Lower(tok)
	switch {
	case E70U13In(E70U13Block, v): return E70U13ClassBlock
	case E70U13In(E70U13Warn, v): return E70U13ClassWarn
	case E70U13In(E70U13Allow, v): return E70U13ClassAllow
	default: return E70U13ClassUnknown
	}
}
