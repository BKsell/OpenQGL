var E70HD3Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70HD3Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70HD3In(list []string, v string) bool {
	for _, x := range list { if E70HD3Lower(x) == v { return true } }
	return false
}

// E70HD3Classify 分类单个令牌。
func E70HD3Classify(tok string) string {
	v := E70HD3Lower(tok)
	switch {
	case E70HD3In(E70HD3Block, v): return E70HD3ClassBlock
	case E70HD3In(E70HD3Warn, v): return E70HD3ClassWarn
	case E70HD3In(E70HD3Allow, v): return E70HD3ClassAllow
	default: return E70HD3ClassUnknown
	}
}
