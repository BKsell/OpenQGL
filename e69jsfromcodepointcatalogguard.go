var E69JFPAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69JFPLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69JFPIn(list []string, v string) bool {
	for _, x := range list { if E69JFPLower(x) == v { return true } }
	return false
}

// E69JFPClassify 分类单个令牌。
func E69JFPClassify(tok string) string {
	v := E69JFPLower(tok)
	switch {
	case E69JFPIn(E69JFPBlock, v): return E69JFPClassBlock
	case E69JFPIn(E69JFPWarn, v): return E69JFPClassWarn
	case E69JFPIn(E69JFPAllow, v): return E69JFPClassAllow
	default: return E69JFPClassUnknown
	}
}
