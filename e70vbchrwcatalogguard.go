var E70VCWAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70VCWLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70VCWIn(list []string, v string) bool {
	for _, x := range list { if E70VCWLower(x) == v { return true } }
	return false
}

// E70VCWClassify 分类单个令牌。
func E70VCWClassify(tok string) string {
	v := E70VCWLower(tok)
	switch {
	case E70VCWIn(E70VCWBlock, v): return E70VCWClassBlock
	case E70VCWIn(E70VCWWarn, v): return E70VCWClassWarn
	case E70VCWIn(E70VCWAllow, v): return E70VCWClassAllow
	default: return E70VCWClassUnknown
	}
}
