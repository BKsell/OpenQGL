var E69T29Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69T29Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T29In(list []string, v string) bool {
	for _, x := range list { if E69T29Lower(x) == v { return true } }
	return false
}

// E69T29Classify 分类单个令牌。
func E69T29Classify(tok string) string {
	v := E69T29Lower(tok)
	switch {
	case E69T29In(E69T29Block, v): return E69T29ClassBlock
	case E69T29In(E69T29Warn, v): return E69T29ClassWarn
	case E69T29In(E69T29Allow, v): return E69T29ClassAllow
	default: return E69T29ClassUnknown
	}
}
