func E69T41Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T41In(list []string, v string) bool {
	for _, x := range list { if E69T41Lower(x) == v { return true } }
	return false
}

// E69T41Classify 分类单个令牌。
func E69T41Classify(tok string) string {
	v := E69T41Lower(tok)
	switch {
	case E69T41In(E69T41Block, v): return E69T41ClassBlock
	case E69T41In(E69T41Warn, v): return E69T41ClassWarn
	case E69T41In(E69T41Allow, v): return E69T41ClassAllow
	default: return E69T41ClassUnknown
	}
}
