var PU3Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func PU3Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func PU3In(list []string, v string) bool {
	for _, x := range list { if PU3Lower(x) == v { return true } }
	return false
}

// PU3Classify 分类单个令牌。
func PU3Classify(tok string) string {
	v := PU3Lower(tok)
	switch {
	case PU3In(PU3Block, v): return PU3ClassBlock
	case PU3In(PU3Warn, v): return PU3ClassWarn
	case PU3In(PU3Allow, v): return PU3ClassAllow
	default: return PU3ClassUnknown
	}
}
