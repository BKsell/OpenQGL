var E70U12Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70U12Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70U12In(list []string, v string) bool {
	for _, x := range list { if E70U12Lower(x) == v { return true } }
	return false
}

// E70U12Classify 分类单个令牌。
func E70U12Classify(tok string) string {
	v := E70U12Lower(tok)
	switch {
	case E70U12In(E70U12Block, v): return E70U12ClassBlock
	case E70U12In(E70U12Warn, v): return E70U12ClassWarn
	case E70U12In(E70U12Allow, v): return E70U12ClassAllow
	default: return E70U12ClassUnknown
	}
}
