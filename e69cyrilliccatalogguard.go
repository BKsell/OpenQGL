var E69T07Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69T07Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T07In(list []string, v string) bool {
	for _, x := range list { if E69T07Lower(x) == v { return true } }
	return false
}

// E69T07Classify 分类单个令牌。
func E69T07Classify(tok string) string {
	v := E69T07Lower(tok)
	switch {
	case E69T07In(E69T07Block, v): return E69T07ClassBlock
	case E69T07In(E69T07Warn, v): return E69T07ClassWarn
	case E69T07In(E69T07Allow, v): return E69T07ClassAllow
	default: return E69T07ClassUnknown
	}
}
