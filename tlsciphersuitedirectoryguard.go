func TLSLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func TLSIn(list []string, v string) bool {
	for _, x := range list { if TLSLower(x) == v { return true } }
	return false
}

// TLSClassify 分类单个令牌。
func TLSClassify(tok string) string {
	v := TLSLower(tok)
	switch {
	case TLSIn(TLSBlock, v): return TLSClassBlock
	case TLSIn(TLSWarn, v): return TLSClassWarn
	case TLSIn(TLSAllow, v): return TLSClassAllow
	default: return TLSClassUnknown
	}
}
