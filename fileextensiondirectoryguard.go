func FEDLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func FEDIn(list []string, v string) bool {
	for _, x := range list { if FEDLower(x) == v { return true } }
	return false
}

// FEDClassify 分类单个令牌。
func FEDClassify(tok string) string {
	v := FEDLower(tok)
	switch {
	case FEDIn(FEDBlock, v): return FEDClassBlock
	case FEDIn(FEDWarn, v): return FEDClassWarn
	case FEDIn(FEDAllow, v): return FEDClassAllow
	default: return FEDClassUnknown
	}
}
