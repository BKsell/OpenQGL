func E69T09Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T09In(list []string, v string) bool {
	for _, x := range list { if E69T09Lower(x) == v { return true } }
	return false
}

// E69T09Classify 分类单个令牌。
func E69T09Classify(tok string) string {
	v := E69T09Lower(tok)
	switch {
	case E69T09In(E69T09Block, v): return E69T09ClassBlock
	case E69T09In(E69T09Warn, v): return E69T09ClassWarn
	case E69T09In(E69T09Allow, v): return E69T09ClassAllow
	default: return E69T09ClassUnknown
	}
}
