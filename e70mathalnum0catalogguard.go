var E70U09Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70U09Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70U09In(list []string, v string) bool {
	for _, x := range list { if E70U09Lower(x) == v { return true } }
	return false
}

// E70U09Classify 分类单个令牌。
func E70U09Classify(tok string) string {
	v := E70U09Lower(tok)
	switch {
	case E70U09In(E70U09Block, v): return E70U09ClassBlock
	case E70U09In(E70U09Warn, v): return E70U09ClassWarn
	case E70U09In(E70U09Allow, v): return E70U09ClassAllow
	default: return E70U09ClassUnknown
	}
}
