var E70PTRAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PTRLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PTRIn(list []string, v string) bool {
	for _, x := range list { if E70PTRLower(x) == v { return true } }
	return false
}

// E70PTRClassify 分类单个令牌。
func E70PTRClassify(tok string) string {
	v := E70PTRLower(tok)
	switch {
	case E70PTRIn(E70PTRBlock, v): return E70PTRClassBlock
	case E70PTRIn(E70PTRWarn, v): return E70PTRClassWarn
	case E70PTRIn(E70PTRAllow, v): return E70PTRClassAllow
	default: return E70PTRClassUnknown
	}
}
