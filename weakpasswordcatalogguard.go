func WPCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func WPCIn(list []string, v string) bool {
	for _, x := range list { if WPCLower(x) == v { return true } }
	return false
}

// WPCClassify 分类单个令牌。
func WPCClassify(tok string) string {
	v := WPCLower(tok)
	switch {
	case WPCIn(WPCBlock, v): return WPCClassBlock
	case WPCIn(WPCWarn, v): return WPCClassWarn
	case WPCIn(WPCAllow, v): return WPCClassAllow
	default: return WPCClassUnknown
	}
}
