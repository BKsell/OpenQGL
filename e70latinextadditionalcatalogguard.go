var E70T35Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70T35Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70T35In(list []string, v string) bool {
	for _, x := range list { if E70T35Lower(x) == v { return true } }
	return false
}

// E70T35Classify 分类单个令牌。
func E70T35Classify(tok string) string {
	v := E70T35Lower(tok)
	switch {
	case E70T35In(E70T35Block, v): return E70T35ClassBlock
	case E70T35In(E70T35Warn, v): return E70T35ClassWarn
	case E70T35In(E70T35Allow, v): return E70T35ClassAllow
	default: return E70T35ClassUnknown
	}
}
