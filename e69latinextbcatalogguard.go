var E69T02Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69T02Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T02In(list []string, v string) bool {
	for _, x := range list { if E69T02Lower(x) == v { return true } }
	return false
}

// E69T02Classify 分类单个令牌。
func E69T02Classify(tok string) string {
	v := E69T02Lower(tok)
	switch {
	case E69T02In(E69T02Block, v): return E69T02ClassBlock
	case E69T02In(E69T02Warn, v): return E69T02ClassWarn
	case E69T02In(E69T02Allow, v): return E69T02ClassAllow
	default: return E69T02ClassUnknown
	}
}
