func VSCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func VSCIn(list []string, v string) bool {
	for _, x := range list { if VSCLower(x) == v { return true } }
	return false
}

// VSCClassify 分类单个令牌。
func VSCClassify(tok string) string {
	v := VSCLower(tok)
	switch {
	case VSCIn(VSCBlock, v): return VSCClassBlock
	case VSCIn(VSCWarn, v): return VSCClassWarn
	case VSCIn(VSCAllow, v): return VSCClassAllow
	default: return VSCClassUnknown
	}
}
