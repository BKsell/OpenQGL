var E70VHCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70VHCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70VHCIn(list []string, v string) bool {
	for _, x := range list { if E70VHCLower(x) == v { return true } }
	return false
}

// E70VHCClassify 分类单个令牌。
func E70VHCClassify(tok string) string {
	v := E70VHCLower(tok)
	switch {
	case E70VHCIn(E70VHCBlock, v): return E70VHCClassBlock
	case E70VHCIn(E70VHCWarn, v): return E70VHCClassWarn
	case E70VHCIn(E70VHCAllow, v): return E70VHCClassAllow
	default: return E70VHCClassUnknown
	}
}
