func E70T62Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70T62In(list []string, v string) bool {
	for _, x := range list { if E70T62Lower(x) == v { return true } }
	return false
}

// E70T62Classify 分类单个令牌。
func E70T62Classify(tok string) string {
	v := E70T62Lower(tok)
	switch {
	case E70T62In(E70T62Block, v): return E70T62ClassBlock
	case E70T62In(E70T62Warn, v): return E70T62ClassWarn
	case E70T62In(E70T62Allow, v): return E70T62ClassAllow
	default: return E70T62ClassUnknown
	}
}
