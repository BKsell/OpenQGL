var E68CULAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68CULLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68CULIn(list []string, v string) bool {
	for _, x := range list { if E68CULLower(x) == v { return true } }
	return false
}

// E68CULClassify 分类单个令牌。
func E68CULClassify(tok string) string {
	v := E68CULLower(tok)
	switch {
	case E68CULIn(E68CULBlock, v): return E68CULClassBlock
	case E68CULIn(E68CULWarn, v): return E68CULClassWarn
	case E68CULIn(E68CULAllow, v): return E68CULClassAllow
	default: return E68CULClassUnknown
	}
}
