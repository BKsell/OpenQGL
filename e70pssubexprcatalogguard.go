var E70PSEAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PSELower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PSEIn(list []string, v string) bool {
	for _, x := range list { if E70PSELower(x) == v { return true } }
	return false
}

// E70PSEClassify 分类单个令牌。
func E70PSEClassify(tok string) string {
	v := E70PSELower(tok)
	switch {
	case E70PSEIn(E70PSEBlock, v): return E70PSEClassBlock
	case E70PSEIn(E70PSEWarn, v): return E70PSEClassWarn
	case E70PSEIn(E70PSEAllow, v): return E70PSEClassAllow
	default: return E70PSEClassUnknown
	}
}
