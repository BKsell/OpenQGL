var E70PMCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PMCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PMCIn(list []string, v string) bool {
	for _, x := range list { if E70PMCLower(x) == v { return true } }
	return false
}

// E70PMCClassify 分类单个令牌。
func E70PMCClassify(tok string) string {
	v := E70PMCLower(tok)
	switch {
	case E70PMCIn(E70PMCBlock, v): return E70PMCClassBlock
	case E70PMCIn(E70PMCWarn, v): return E70PMCClassWarn
	case E70PMCIn(E70PMCAllow, v): return E70PMCClassAllow
	default: return E70PMCClassUnknown
	}
}
