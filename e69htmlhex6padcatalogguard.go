var E69H6PAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69H6PLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69H6PIn(list []string, v string) bool {
	for _, x := range list { if E69H6PLower(x) == v { return true } }
	return false
}

// E69H6PClassify 分类单个令牌。
func E69H6PClassify(tok string) string {
	v := E69H6PLower(tok)
	switch {
	case E69H6PIn(E69H6PBlock, v): return E69H6PClassBlock
	case E69H6PIn(E69H6PWarn, v): return E69H6PClassWarn
	case E69H6PIn(E69H6PAllow, v): return E69H6PClassAllow
	default: return E69H6PClassUnknown
	}
}
