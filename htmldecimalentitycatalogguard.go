var HDEAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func HDELower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func HDEIn(list []string, v string) bool {
	for _, x := range list { if HDELower(x) == v { return true } }
	return false
}

// HDEClassify 分类单个令牌。
func HDEClassify(tok string) string {
	v := HDELower(tok)
	switch {
	case HDEIn(HDEBlock, v): return HDEClassBlock
	case HDEIn(HDEWarn, v): return HDEClassWarn
	case HDEIn(HDEAllow, v): return HDEClassAllow
	default: return HDEClassUnknown
	}
}
