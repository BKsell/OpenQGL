var E69HNSAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69HNSLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69HNSIn(list []string, v string) bool {
	for _, x := range list { if E69HNSLower(x) == v { return true } }
	return false
}

// E69HNSClassify 分类单个令牌。
func E69HNSClassify(tok string) string {
	v := E69HNSLower(tok)
	switch {
	case E69HNSIn(E69HNSBlock, v): return E69HNSClassBlock
	case E69HNSIn(E69HNSWarn, v): return E69HNSClassWarn
	case E69HNSIn(E69HNSAllow, v): return E69HNSClassAllow
	default: return E69HNSClassUnknown
	}
}
