var E70PBDAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PBDLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PBDIn(list []string, v string) bool {
	for _, x := range list { if E70PBDLower(x) == v { return true } }
	return false
}

// E70PBDClassify 分类单个令牌。
func E70PBDClassify(tok string) string {
	v := E70PBDLower(tok)
	switch {
	case E70PBDIn(E70PBDBlock, v): return E70PBDClassBlock
	case E70PBDIn(E70PBDWarn, v): return E70PBDClassWarn
	case E70PBDIn(E70PBDAllow, v): return E70PBDClassAllow
	default: return E70PBDClassUnknown
	}
}
