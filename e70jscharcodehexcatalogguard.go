var E70JCHAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70JCHLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70JCHIn(list []string, v string) bool {
	for _, x := range list { if E70JCHLower(x) == v { return true } }
	return false
}

// E70JCHClassify 分类单个令牌。
func E70JCHClassify(tok string) string {
	v := E70JCHLower(tok)
	switch {
	case E70JCHIn(E70JCHBlock, v): return E70JCHClassBlock
	case E70JCHIn(E70JCHWarn, v): return E70JCHClassWarn
	case E70JCHIn(E70JCHAllow, v): return E70JCHClassAllow
	default: return E70JCHClassUnknown
	}
}
