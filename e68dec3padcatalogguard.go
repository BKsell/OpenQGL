var E68D03Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68D03Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68D03In(list []string, v string) bool {
	for _, x := range list { if E68D03Lower(x) == v { return true } }
	return false
}

// E68D03Classify 分类单个令牌。
func E68D03Classify(tok string) string {
	v := E68D03Lower(tok)
	switch {
	case E68D03In(E68D03Block, v): return E68D03ClassBlock
	case E68D03In(E68D03Warn, v): return E68D03ClassWarn
	case E68D03In(E68D03Allow, v): return E68D03ClassAllow
	default: return E68D03ClassUnknown
	}
}
