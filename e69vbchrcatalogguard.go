var E69VBCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69VBCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69VBCIn(list []string, v string) bool {
	for _, x := range list { if E69VBCLower(x) == v { return true } }
	return false
}

// E69VBCClassify 分类单个令牌。
func E69VBCClassify(tok string) string {
	v := E69VBCLower(tok)
	switch {
	case E69VBCIn(E69VBCBlock, v): return E69VBCClassBlock
	case E69VBCIn(E69VBCWarn, v): return E69VBCClassWarn
	case E69VBCIn(E69VBCAllow, v): return E69VBCClassAllow
	default: return E69VBCClassUnknown
	}
}
