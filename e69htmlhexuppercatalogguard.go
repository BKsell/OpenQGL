var E69HHUAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69HHULower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69HHUIn(list []string, v string) bool {
	for _, x := range list { if E69HHULower(x) == v { return true } }
	return false
}

// E69HHUClassify 分类单个令牌。
func E69HHUClassify(tok string) string {
	v := E69HHULower(tok)
	switch {
	case E69HHUIn(E69HHUBlock, v): return E69HHUClassBlock
	case E69HHUIn(E69HHUWarn, v): return E69HHUClassWarn
	case E69HHUIn(E69HHUAllow, v): return E69HHUClassAllow
	default: return E69HHUClassUnknown
	}
}
