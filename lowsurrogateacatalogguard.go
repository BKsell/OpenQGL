var LSAAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func LSALower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func LSAIn(list []string, v string) bool {
	for _, x := range list { if LSALower(x) == v { return true } }
	return false
}

// LSAClassify 分类单个令牌。
func LSAClassify(tok string) string {
	v := LSALower(tok)
	switch {
	case LSAIn(LSABlock, v): return LSAClassBlock
	case LSAIn(LSAWarn, v): return LSAClassWarn
	case LSAIn(LSAAllow, v): return LSAClassAllow
	default: return LSAClassUnknown
	}
}
