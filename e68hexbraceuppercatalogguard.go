var E68HXUAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68HXULower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68HXUIn(list []string, v string) bool {
	for _, x := range list { if E68HXULower(x) == v { return true } }
	return false
}

// E68HXUClassify 分类单个令牌。
func E68HXUClassify(tok string) string {
	v := E68HXULower(tok)
	switch {
	case E68HXUIn(E68HXUBlock, v): return E68HXUClassBlock
	case E68HXUIn(E68HXUWarn, v): return E68HXUClassWarn
	case E68HXUIn(E68HXUAllow, v): return E68HXUClassAllow
	default: return E68HXUClassUnknown
	}
}
