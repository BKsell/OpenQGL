var E69U7SAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69U7SLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69U7SIn(list []string, v string) bool {
	for _, x := range list { if E69U7SLower(x) == v { return true } }
	return false
}

// E69U7SClassify 分类单个令牌。
func E69U7SClassify(tok string) string {
	v := E69U7SLower(tok)
	switch {
	case E69U7SIn(E69U7SBlock, v): return E69U7SClassBlock
	case E69U7SIn(E69U7SWarn, v): return E69U7SClassWarn
	case E69U7SIn(E69U7SAllow, v): return E69U7SClassAllow
	default: return E69U7SClassUnknown
	}
}
