var E70T02Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70T02Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70T02In(list []string, v string) bool {
	for _, x := range list { if E70T02Lower(x) == v { return true } }
	return false
}

// E70T02Classify 分类单个令牌。
func E70T02Classify(tok string) string {
	v := E70T02Lower(tok)
	switch {
	case E70T02In(E70T02Block, v): return E70T02ClassBlock
	case E70T02In(E70T02Warn, v): return E70T02ClassWarn
	case E70T02In(E70T02Allow, v): return E70T02ClassAllow
	default: return E70T02ClassUnknown
	}
}
