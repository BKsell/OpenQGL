var E69T36Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69T36Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69T36In(list []string, v string) bool {
	for _, x := range list { if E69T36Lower(x) == v { return true } }
	return false
}

// E69T36Classify 分类单个令牌。
func E69T36Classify(tok string) string {
	v := E69T36Lower(tok)
	switch {
	case E69T36In(E69T36Block, v): return E69T36ClassBlock
	case E69T36In(E69T36Warn, v): return E69T36ClassWarn
	case E69T36In(E69T36Allow, v): return E69T36ClassAllow
	default: return E69T36ClassUnknown
	}
}
