var E70HD6Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70HD6Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70HD6In(list []string, v string) bool {
	for _, x := range list { if E70HD6Lower(x) == v { return true } }
	return false
}

// E70HD6Classify 分类单个令牌。
func E70HD6Classify(tok string) string {
	v := E70HD6Lower(tok)
	switch {
	case E70HD6In(E70HD6Block, v): return E70HD6ClassBlock
	case E70HD6In(E70HD6Warn, v): return E70HD6ClassWarn
	case E70HD6In(E70HD6Allow, v): return E70HD6ClassAllow
	default: return E70HD6ClassUnknown
	}
}
