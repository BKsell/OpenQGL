func IMDLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func IMDIn(list []string, v string) bool {
	for _, x := range list { if IMDLower(x) == v { return true } }
	return false
}

// IMDClassify 分类单个令牌。
func IMDClassify(tok string) string {
	v := IMDLower(tok)
	switch {
	case IMDIn(IMDBlock, v): return IMDClassBlock
	case IMDIn(IMDWarn, v): return IMDClassWarn
	case IMDIn(IMDAllow, v): return IMDClassAllow
	default: return IMDClassUnknown
	}
}
