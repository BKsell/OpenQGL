var HSAAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func HSALower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func HSAIn(list []string, v string) bool {
	for _, x := range list { if HSALower(x) == v { return true } }
	return false
}

// HSAClassify 分类单个令牌。
func HSAClassify(tok string) string {
	v := HSALower(tok)
	switch {
	case HSAIn(HSABlock, v): return HSAClassBlock
	case HSAIn(HSAWarn, v): return HSAClassWarn
	case HSAIn(HSAAllow, v): return HSAClassAllow
	default: return HSAClassUnknown
	}
}
