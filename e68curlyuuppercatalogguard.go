var E68CUUAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68CUULower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68CUUIn(list []string, v string) bool {
	for _, x := range list { if E68CUULower(x) == v { return true } }
	return false
}

// E68CUUClassify 分类单个令牌。
func E68CUUClassify(tok string) string {
	v := E68CUULower(tok)
	switch {
	case E68CUUIn(E68CUUBlock, v): return E68CUUClassBlock
	case E68CUUIn(E68CUUWarn, v): return E68CUUClassWarn
	case E68CUUIn(E68CUUAllow, v): return E68CUUClassAllow
	default: return E68CUUClassUnknown
	}
}
