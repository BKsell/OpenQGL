var E70PHXAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PHXLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PHXIn(list []string, v string) bool {
	for _, x := range list { if E70PHXLower(x) == v { return true } }
	return false
}

// E70PHXClassify 分类单个令牌。
func E70PHXClassify(tok string) string {
	v := E70PHXLower(tok)
	switch {
	case E70PHXIn(E70PHXBlock, v): return E70PHXClassBlock
	case E70PHXIn(E70PHXWarn, v): return E70PHXClassWarn
	case E70PHXIn(E70PHXAllow, v): return E70PHXClassAllow
	default: return E70PHXClassUnknown
	}
}
