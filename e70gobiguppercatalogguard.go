var E70GBUAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70GBULower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70GBUIn(list []string, v string) bool {
	for _, x := range list { if E70GBULower(x) == v { return true } }
	return false
}

// E70GBUClassify 分类单个令牌。
func E70GBUClassify(tok string) string {
	v := E70GBULower(tok)
	switch {
	case E70GBUIn(E70GBUBlock, v): return E70GBUClassBlock
	case E70GBUIn(E70GBUWarn, v): return E70GBUClassWarn
	case E70GBUIn(E70GBUAllow, v): return E70GBUClassAllow
	default: return E70GBUClassUnknown
	}
}
