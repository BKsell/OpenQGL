var E69XLFAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69XLFLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69XLFIn(list []string, v string) bool {
	for _, x := range list { if E69XLFLower(x) == v { return true } }
	return false
}

// E69XLFClassify 分类单个令牌。
func E69XLFClassify(tok string) string {
	v := E69XLFLower(tok)
	switch {
	case E69XLFIn(E69XLFBlock, v): return E69XLFClassBlock
	case E69XLFIn(E69XLFWarn, v): return E69XLFClassWarn
	case E69XLFIn(E69XLFAllow, v): return E69XLFClassAllow
	default: return E69XLFClassUnknown
	}
}
