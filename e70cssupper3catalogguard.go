var E70C3UAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70C3ULower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70C3UIn(list []string, v string) bool {
	for _, x := range list { if E70C3ULower(x) == v { return true } }
	return false
}

// E70C3UClassify 分类单个令牌。
func E70C3UClassify(tok string) string {
	v := E70C3ULower(tok)
	switch {
	case E70C3UIn(E70C3UBlock, v): return E70C3UClassBlock
	case E70C3UIn(E70C3UWarn, v): return E70C3UClassWarn
	case E70C3UIn(E70C3UAllow, v): return E70C3UClassAllow
	default: return E70C3UClassUnknown
	}
}
