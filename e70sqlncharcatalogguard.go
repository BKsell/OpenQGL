var E70SNCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70SNCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70SNCIn(list []string, v string) bool {
	for _, x := range list { if E70SNCLower(x) == v { return true } }
	return false
}

// E70SNCClassify 分类单个令牌。
func E70SNCClassify(tok string) string {
	v := E70SNCLower(tok)
	switch {
	case E70SNCIn(E70SNCBlock, v): return E70SNCClassBlock
	case E70SNCIn(E70SNCWarn, v): return E70SNCClassWarn
	case E70SNCIn(E70SNCAllow, v): return E70SNCClassAllow
	default: return E70SNCClassUnknown
	}
}
