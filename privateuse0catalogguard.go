var PU0Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func PU0Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func PU0In(list []string, v string) bool {
	for _, x := range list { if PU0Lower(x) == v { return true } }
	return false
}

// PU0Classify 分类单个令牌。
func PU0Classify(tok string) string {
	v := PU0Lower(tok)
	switch {
	case PU0In(PU0Block, v): return PU0ClassBlock
	case PU0In(PU0Warn, v): return PU0ClassWarn
	case PU0In(PU0Allow, v): return PU0ClassAllow
	default: return PU0ClassUnknown
	}
}
