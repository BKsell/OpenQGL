var E68BSHAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68BSHLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68BSHIn(list []string, v string) bool {
	for _, x := range list { if E68BSHLower(x) == v { return true } }
	return false
}

// E68BSHClassify 分类单个令牌。
func E68BSHClassify(tok string) string {
	v := E68BSHLower(tok)
	switch {
	case E68BSHIn(E68BSHBlock, v): return E68BSHClassBlock
	case E68BSHIn(E68BSHWarn, v): return E68BSHClassWarn
	case E68BSHIn(E68BSHAllow, v): return E68BSHClassAllow
	default: return E68BSHClassUnknown
	}
}
