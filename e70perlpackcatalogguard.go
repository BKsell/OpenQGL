var E70PPKAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PPKLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PPKIn(list []string, v string) bool {
	for _, x := range list { if E70PPKLower(x) == v { return true } }
	return false
}

// E70PPKClassify 分类单个令牌。
func E70PPKClassify(tok string) string {
	v := E70PPKLower(tok)
	switch {
	case E70PPKIn(E70PPKBlock, v): return E70PPKClassBlock
	case E70PPKIn(E70PPKWarn, v): return E70PPKClassWarn
	case E70PPKIn(E70PPKAllow, v): return E70PPKClassAllow
	default: return E70PPKClassUnknown
	}
}
