var E68O03Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68O03Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68O03In(list []string, v string) bool {
	for _, x := range list { if E68O03Lower(x) == v { return true } }
	return false
}

// E68O03Classify 分类单个令牌。
func E68O03Classify(tok string) string {
	v := E68O03Lower(tok)
	switch {
	case E68O03In(E68O03Block, v): return E68O03ClassBlock
	case E68O03In(E68O03Warn, v): return E68O03ClassWarn
	case E68O03In(E68O03Allow, v): return E68O03ClassAllow
	default: return E68O03ClassUnknown
	}
}
