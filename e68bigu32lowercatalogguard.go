var E68BGLAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E68BGLLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E68BGLIn(list []string, v string) bool {
	for _, x := range list { if E68BGLLower(x) == v { return true } }
	return false
}

// E68BGLClassify 分类单个令牌。
func E68BGLClassify(tok string) string {
	v := E68BGLLower(tok)
	switch {
	case E68BGLIn(E68BGLBlock, v): return E68BGLClassBlock
	case E68BGLIn(E68BGLWarn, v): return E68BGLClassWarn
	case E68BGLIn(E68BGLAllow, v): return E68BGLClassAllow
	default: return E68BGLClassUnknown
	}
}
