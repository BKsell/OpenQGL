var PU2Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func PU2Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func PU2In(list []string, v string) bool {
	for _, x := range list { if PU2Lower(x) == v { return true } }
	return false
}

// PU2Classify 分类单个令牌。
func PU2Classify(tok string) string {
	v := PU2Lower(tok)
	switch {
	case PU2In(PU2Block, v): return PU2ClassBlock
	case PU2In(PU2Warn, v): return PU2ClassWarn
	case PU2In(PU2Allow, v): return PU2ClassAllow
	default: return PU2ClassUnknown
	}
}
