var E70PTDAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PTDLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PTDIn(list []string, v string) bool {
	for _, x := range list { if E70PTDLower(x) == v { return true } }
	return false
}

// E70PTDClassify 分类单个令牌。
func E70PTDClassify(tok string) string {
	v := E70PTDLower(tok)
	switch {
	case E70PTDIn(E70PTDBlock, v): return E70PTDClassBlock
	case E70PTDIn(E70PTDWarn, v): return E70PTDClassWarn
	case E70PTDIn(E70PTDAllow, v): return E70PTDClassAllow
	default: return E70PTDClassUnknown
	}
}
