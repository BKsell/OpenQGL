var E70PUCAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70PUCLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70PUCIn(list []string, v string) bool {
	for _, x := range list { if E70PUCLower(x) == v { return true } }
	return false
}

// E70PUCClassify 分类单个令牌。
func E70PUCClassify(tok string) string {
	v := E70PUCLower(tok)
	switch {
	case E70PUCIn(E70PUCBlock, v): return E70PUCClassBlock
	case E70PUCIn(E70PUCWarn, v): return E70PUCClassWarn
	case E70PUCIn(E70PUCAllow, v): return E70PUCClassAllow
	default: return E70PUCClassUnknown
	}
}
