var E70U11Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70U11Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70U11In(list []string, v string) bool {
	for _, x := range list { if E70U11Lower(x) == v { return true } }
	return false
}

// E70U11Classify 分类单个令牌。
func E70U11Classify(tok string) string {
	v := E70U11Lower(tok)
	switch {
	case E70U11In(E70U11Block, v): return E70U11ClassBlock
	case E70U11In(E70U11Warn, v): return E70U11ClassWarn
	case E70U11In(E70U11Allow, v): return E70U11ClassAllow
	default: return E70U11ClassUnknown
	}
}
