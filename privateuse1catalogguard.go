var PU1Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func PU1Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func PU1In(list []string, v string) bool {
	for _, x := range list { if PU1Lower(x) == v { return true } }
	return false
}

// PU1Classify 分类单个令牌。
func PU1Classify(tok string) string {
	v := PU1Lower(tok)
	switch {
	case PU1In(PU1Block, v): return PU1ClassBlock
	case PU1In(PU1Warn, v): return PU1ClassWarn
	case PU1In(PU1Allow, v): return PU1ClassAllow
	default: return PU1ClassUnknown
	}
}
