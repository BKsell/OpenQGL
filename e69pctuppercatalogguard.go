var E69PUBAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E69PUBLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E69PUBIn(list []string, v string) bool {
	for _, x := range list { if E69PUBLower(x) == v { return true } }
	return false
}

// E69PUBClassify 分类单个令牌。
func E69PUBClassify(tok string) string {
	v := E69PUBLower(tok)
	switch {
	case E69PUBIn(E69PUBBlock, v): return E69PUBClassBlock
	case E69PUBIn(E69PUBWarn, v): return E69PUBClassWarn
	case E69PUBIn(E69PUBAllow, v): return E69PUBClassAllow
	default: return E69PUBClassUnknown
	}
}
