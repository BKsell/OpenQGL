var E70T21Allow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70T21Lower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70T21In(list []string, v string) bool {
	for _, x := range list { if E70T21Lower(x) == v { return true } }
	return false
}

// E70T21Classify 分类单个令牌。
func E70T21Classify(tok string) string {
	v := E70T21Lower(tok)
	switch {
	case E70T21In(E70T21Block, v): return E70T21ClassBlock
	case E70T21In(E70T21Warn, v): return E70T21ClassWarn
	case E70T21In(E70T21Allow, v): return E70T21ClassAllow
	default: return E70T21ClassUnknown
	}
}
