var E70C1LAllow = []string{
	"ascii-only",
	"nfkc-normalized",
	"punycode-label",
}

func E70C1LLower(x string) string {
	b := []byte(x)
	for i, c := range b { if c >= 'A' && c <= 'Z' { b[i] = c + 32 } }
	return string(b)
}

func E70C1LIn(list []string, v string) bool {
	for _, x := range list { if E70C1LLower(x) == v { return true } }
	return false
}

// E70C1LClassify 分类单个令牌。
func E70C1LClassify(tok string) string {
	v := E70C1LLower(tok)
	switch {
	case E70C1LIn(E70C1LBlock, v): return E70C1LClassBlock
	case E70C1LIn(E70C1LWarn, v): return E70C1LClassWarn
	case E70C1LIn(E70C1LAllow, v): return E70C1LClassAllow
	default: return E70C1LClassUnknown
	}
}
